/**
 * Copies the compiled SecureVote ABI into packages/contracts/abi so the backend and
 * frontend can import it as `@securevote/contracts` without depending on Hardhat.
 * The ABI is public interface information — it contains no secrets.
 */
const fs = require("node:fs");
const path = require("node:path");

const artifactPath = path.join(__dirname, "..", "artifacts", "contracts", "SecureVote.sol", "SecureVote.json");
const outDir = path.join(__dirname, "..", "abi");
const { abi, contractName } = JSON.parse(fs.readFileSync(artifactPath, "utf8"));
const json = JSON.stringify(abi, null, 2);

fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(path.join(outDir, "SecureVote.json"), json + "\n");
const header = "// AUTO-GENERATED by scripts/export-abi.cjs — do not edit by hand.\n";
fs.writeFileSync(path.join(outDir, "index.mjs"), `${header}export const secureVoteAbi = ${json};\n`);
fs.writeFileSync(path.join(outDir, "index.cjs"), `${header}module.exports = { secureVoteAbi: ${json} };\n`);
fs.writeFileSync(
  path.join(outDir, "index.d.ts"),
  `${header}export interface AbiParam {
  readonly name?: string;
  readonly type?: string;
  readonly internalType?: string;
  readonly indexed?: boolean;
  readonly components?: readonly AbiParam[];
}
export interface AbiEntry {
  readonly type?: string;
  readonly name?: string;
  readonly inputs?: readonly AbiParam[];
  readonly outputs?: readonly AbiParam[];
  readonly stateMutability?: string;
  readonly anonymous?: boolean;
}
/** JSON ABI of SecureVote.sol (compatible with ethers' JsonFragment[]). */
export declare const secureVoteAbi: readonly AbiEntry[];
`,
);
console.log(`Exported ${contractName} ABI (${abi.length} entries) to ${path.relative(process.cwd(), outDir)}/`);
